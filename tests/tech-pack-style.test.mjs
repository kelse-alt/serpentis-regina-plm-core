import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createTechPack, normalizeTechPack, migrateTechPack, sharedStyleKey, resolveFieldValue, compareTechPacks, parseMeasure, formatMeasure, columnsForRow } from '../src/tech-pack.mjs';

const template = JSON.parse(await readFile(new URL('../data/templates/tech-pack-workbook.v1.json', import.meta.url), 'utf8'));
const legacyPack = () => {
  const pack = createTechPack(template);
  delete pack.style;
  pack.schemaVersion = 1;
  return pack;
};

test('new packs share blank style defaults without prefilled specifications or changed source schema', () => {
  const sourceBefore = structuredClone(template);
  const pack = createTechPack(template);
  assert.equal(pack.schemaVersion, 2);
  assert.deepEqual(pack.style, { number: '', description: '', category: '', season: '', baseSize: '', sampleSize: '', maker: '', patternRevision: '', owner: '', fabric: '' });
  assert.equal(pack.unit, null);
  assert.deepEqual(normalizeTechPack(pack, template), pack);
  assert.deepEqual(template, sourceBefore);
});

test('shared style defaults resolve only like-for-like fields while explicit sample and sheet overrides stay independent', () => {
  const pack = createTechPack(template);
  Object.assign(pack.style, { number: 'SR-001', description: 'House jacket', category: 'Jacket', season: 'AW27', baseSize: '8', sampleSize: '10', maker: 'Studio maker', fabric: 'Twill', patternRevision: 'P03', owner: 'Designer' });
  assert.equal(resolveFieldValue(pack, 'pattern', 'style'), 'SR-001');
  assert.equal(resolveFieldValue(pack, 'pattern', 'styleNumber'), 'SR-001');
  assert.equal(resolveFieldValue(pack, 'fit', 'style'), 'SR-001');
  assert.equal(resolveFieldValue(pack, 'master', 'style'), 'SR-001');
  assert.equal(resolveFieldValue(pack, 'graded', 'selfFabric'), 'Twill');
  assert.equal(resolveFieldValue(pack, 'fit', 'sampleSize'), '10');
  assert.equal(resolveFieldValue(pack, 'pattern', 'size'), '8');
  assert.equal(resolveFieldValue(pack, 'wash', 'asampleSize'), '10');
  assert.equal(resolveFieldValue(pack, 'wash', 'bsampleSize'), '10');
  assert.equal(resolveFieldValue(pack, 'wash', 'aseason'), 'AW27');
  assert.equal(resolveFieldValue(pack, 'wash', 'bseason'), 'AW27');
  assert.equal(resolveFieldValue(pack, 'graded', 'patternNumber'), '');
  assert.equal(resolveFieldValue(pack, 'master', 'revision'), '');
  for (const [sheet, field] of [['wash', 'asampleStage'], ['wash', 'bsampleStage'], ['wash', 'adate'], ['wash', 'bdate'], ['fit', 'stage'], ['fit', 'refPattern'], ['pattern', 'gradedRevision'], ['body', 'measuredBy']]) assert.equal(sharedStyleKey(sheet, field), null);
  pack.fields.wash.asampleSize = '6';
  pack.fields.wash.aseason = 'SS28';
  assert.equal(resolveFieldValue(pack, 'wash', 'bsampleSize'), '10', 'Round A does not change the blank Round B baseline.');
  assert.equal(resolveFieldValue(pack, 'wash', 'bseason'), 'AW27');
  assert.equal(pack.style.sampleSize, '10');
  assert.equal(pack.style.season, 'AW27');
  pack.fields.wash.bsampleSize = '12';
  pack.fields.fit.sampleSize = '14';
  pack.fields.master.fabric = 'Sample-specific wool';
  pack.fields.pattern.style = 'PATTERN-OVERRIDE';
  assert.equal(resolveFieldValue(pack, 'wash', 'asampleSize'), '6');
  assert.equal(resolveFieldValue(pack, 'wash', 'aseason'), 'SS28');
  assert.equal(resolveFieldValue(pack, 'wash', 'bsampleSize'), '12');
  assert.equal(resolveFieldValue(pack, 'fit', 'sampleSize'), '14');
  assert.equal(resolveFieldValue(pack, 'master', 'fabric'), 'Sample-specific wool');
  assert.equal(resolveFieldValue(pack, 'fit', 'style'), 'PATTERN-OVERRIDE');
  pack.fields.master.fabric = '  ';
  assert.equal(resolveFieldValue(pack, template.sheets.find(s => s.id === 'master'), { key: 'fabric' }), 'Twill');
  assert.equal(pack.fields.master.fabric, '  ', 'Resolving a default does not rewrite the stored override.');
});

test('v1 migration preserves explicit conflicts, measurements, image bytes, IDs and source manual formula cells', () => {
  const legacy = legacyPack();
  legacy.unit = 'in';
  legacy.fields.pattern.styleNumber = 'SR-001';
  legacy.fields.pattern.style = 'SR-001';
  legacy.fields.pattern.size = '8';
  legacy.fields.pattern.fabric = 'House twill';
  legacy.fields.master.style = 'SR-OTHER';
  legacy.fields.master.description = 'Original jacket';
  legacy.fields.master.sampleSize = '10';
  legacy.fields.fit.sampleSize = '12';
  legacy.fields.wash.asampleSize = '6';
  legacy.fields.wash.bsampleSize = '14';
  legacy.fields.master.revision = 'PAGE 2';
  legacy.fields.graded.patternNumber = 'PAT-9';
  legacy.tables.master.specs['1'].base = 61.9125;
  legacy.tables.master.specs['1'].actual = 63.1825;
  legacy.tables.wash.measurements['30'].adelta = -1.27;
  const slot = Object.keys(legacy.attachments.pattern)[0];
  legacy.attachments.pattern[slot] = { name: 'flat.png', type: 'image/png', dataUrl: 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j0QAAAABJRU5ErkJggg==' };
  const original = structuredClone(legacy);
  const migrated = migrateTechPack(legacy, template);
  assert.equal(migrated.schemaVersion, 2);
  assert.equal(migrated.style.number, 'SR-001');
  assert.equal(migrated.style.description, 'Original jacket');
  assert.equal(migrated.style.baseSize, '8');
  assert.equal(migrated.style.sampleSize, '10');
  assert.equal(migrated.style.fabric, 'House twill');
  assert.equal(migrated.style.patternRevision, '');
  assert.equal(migrated.style.owner, '');
  assert.equal(resolveFieldValue(migrated, 'master', 'style'), 'SR-OTHER');
  assert.equal(resolveFieldValue(migrated, 'fit', 'sampleSize'), '12');
  for (const key of ['fields', 'tables', 'attachments', 'id', 'title', 'unit', 'updatedAt']) assert.deepEqual(migrated[key], original[key]);
  assert.deepEqual(legacy, original);
  assert.deepEqual(normalizeTechPack(legacy, template), migrated);
  assert.deepEqual(migrateTechPack(migrated, template), migrated);
  assert.deepEqual(normalizeTechPack(JSON.parse(JSON.stringify(migrated)), template), migrated);
  const wash = template.sheets.find(s => s.id === 'wash').tables[0];
  assert.equal(columnsForRow(wash, wash.rows.find(row => row.id === '30')).find(c => c.key === 'adelta').type, 'measurement');
  assert.ok(!Object.hasOwn(migrated.tables.wash.measurements['1'], 'adelta'));
});

test('ambiguous v1 identifiers are not silently reconciled and malformed legacy/current data is refused', () => {
  const legacy = legacyPack();
  legacy.fields.pattern.style = 'PATTERN-A';
  legacy.fields.pattern.styleNumber = 'STYLE-B';
  legacy.fields.master.style = 'STYLE-B';
  const migrated = migrateTechPack(legacy, template);
  assert.equal(migrated.style.number, '');
  assert.equal(migrated.fields.pattern.style, 'PATTERN-A');
  assert.equal(migrated.fields.pattern.styleNumber, 'STYLE-B');
  assert.equal(resolveFieldValue(migrated, 'fit', 'style'), 'PATTERN-A');
  const unknownLegacy = structuredClone(legacy);
  unknownLegacy.unknown = 'Do not discard';
  assert.throws(() => migrateTechPack(unknownLegacy, template), /known template fields/);
  const unknownStyle = createTechPack(template);
  unknownStyle.style.approved = true;
  assert.throws(() => normalizeTechPack(unknownStyle, template), /known template fields/);
  const missingStyle = createTechPack(template);
  delete missingStyle.style.owner;
  assert.throws(() => normalizeTechPack(missingStyle, template));
  const badStyle = createTechPack(template);
  badStyle.style.number = 12;
  assert.throws(() => normalizeTechPack(badStyle, template), /must be text/);
});

test('revision comparison identifies meaningful metadata, spec, missing-value and image changes without embedding images', () => {
  const before = createTechPack(template), after = structuredClone(before);
  after.id = 'another-identity';
  after.updatedAt = '2026-10-23T12:00:00.000Z';
  assert.deepEqual(compareTechPacks(before, after), []);
  after.style.number = 'SR-002';
  after.title = 'Jacket';
  after.unit = 'cm';
  after.fields.master.description = 'Sample-specific';
  after.tables.master.specs['1'].actual = 0;
  const slot = Object.keys(after.attachments.pattern)[0];
  after.attachments.pattern[slot] = { name: 'flat.png', type: 'image/png', dataUrl: 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j0QAAAABJRU5ErkJggg==' };
  const frozenBefore = structuredClone(before), frozenAfter = structuredClone(after);
  const changes = compareTechPacks(before, after);
  assert.equal(changes.length, 6);
  assert.deepEqual(changes.find(c => c.path === 'style.number'), { path: 'style.number', before: '', after: 'SR-002' });
  assert.deepEqual(changes.find(c => c.path === 'tables.master.specs.1.actual'), { path: 'tables.master.specs.1.actual', before: null, after: 0 });
  const image = changes.find(c => c.path === `attachments.pattern.${slot}`);
  assert.equal(image.before, null);
  assert.equal(image.after.name, 'flat.png');
  assert.ok(image.after.bytes > 0);
  assert.match(image.after.contentFingerprint, /^[a-f\d]{8}$/);
  assert.ok(!JSON.stringify(changes).includes('data:image'));
  assert.deepEqual(before, frozenBefore);
  assert.deepEqual(after, frozenAfter);
  const replacement = structuredClone(after);
  replacement.attachments.pattern[slot].dataUrl += 'AAAA';
  assert.equal(compareTechPacks(after, replacement).length, 1, 'Replacing image content with the same filename still produces a change.');
});

test('IN tape fractions accept simple and mixed notation without making decimal CM or quantity rules ambiguous', () => {
  assert.equal(parseMeasure('1/2', 'in'), 1.27);
  assert.equal(parseMeasure('24 3/8', 'in'), 61.9125);
  assert.equal(parseMeasure('  +24 3/8  ', 'in'), 61.9125);
  assert.equal(parseMeasure('-1/2', 'in', { allowNegative: true }), -1.27);
  assert.equal(parseMeasure('-24 3/8', 'in', { allowNegative: true }), -61.9125);
  assert.equal(parseMeasure('0/8', 'in'), 0);
  assert.equal(formatMeasure(parseMeasure('24 3/8', 'in'), 'in'), '24.375');
  for (const value of ['1/0', '24 3/0', '24 8/8', '1 / 2', '24-3/8', '1/2/3', '-1/2', '3.5/8', '1/' + '9'.repeat(400)]) assert.throws(() => parseMeasure(value, 'in'));
  for (const value of ['1/2', '24 3/8', '-1/2']) assert.throws(() => parseMeasure(value, 'cm', { allowNegative: true }));
});
